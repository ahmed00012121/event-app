const Reg = require("../models/reg");
const Event = require("../models/event");
const { sendMail } = require("../utils/mail");
const CLIENT_URL = process.env.CLIENT_URL || 'http://localhost:3000';

// -------------------------
// Register for an event (Student)
// -------------------------
const registerEvent = async (req, res) => {
    try {
        const { eventId } = req.body;

        if (!eventId) {
            return res.status(400).json({ message: "Event ID is required" });
        }

        const event = await Event.findById(eventId);
        if (!event) {
            return res.status(404).json({ message: "Event not found" });
        }

        const alreadyRegistered = await Reg.findOne({
            event: eventId,
            student: req.user.id
        });

        if (alreadyRegistered) {
            return res.status(400).json({ message: "Already registered for this event" });
        }

        // create registration - attendanceCode will be auto-generated by model
        const reg = await Reg.create({
            event: eventId,
            student: req.user.id,
            status: "pending",
            // ticket will be populated after creation
        });

        // ensure we have populated event/student for frontend
        await reg.populate([
            { path: "student", select: "name email" },
            { path: "event", select: "title startDateTime endDateTime" }
        ]);

        // attach a basic ticket object (number = attendanceCode, qr payload = attendanceCode)
        reg.ticket = {
            number: reg.attendanceCode,
            issuedAt: new Date(),
            qr: reg.attendanceCode,
            emailed: false
        };

        await reg.save();

        res.status(201).json(reg);
    } catch (err) {
        res.status(500).json({ message: err.message });
    }
};

// -------------------------
// Get all registrations (Admin/Student)
// -------------------------
const getRegistrations = async (req, res) => {
    try {
        let filter = {};

        if (req.user.role === "student") {
            filter.student = req.user.id;
        }

        const regs = await Reg.find(filter)
            .populate("student", "name email")
            .populate("event", "title startDateTime endDateTime");

        res.json(regs);
    } catch (err) {
        res.status(500).json({ message: err.message });
    }
};

// -------------------------
// Verify attendance code (Admin)
// -------------------------
const verifyAttendanceCode = async (req, res) => {
    try {
        const { attendanceCode } = req.body;

        const reg = await Reg.findOne({ attendanceCode })
            .populate("student", "name")
            .populate("event", "title");

        if (!reg) {
            return res.status(404).json({ message: "Invalid code" });
        }

        // Student self-verifies their code when at the event.
        // Do not mark 'attended' yet — admin must finalize attendance.
        reg.studentVerified = true;
        reg.studentVerifiedAt = new Date();

        await reg.save();

        res.json({ message: "Code accepted — awaiting admin confirmation", registration: reg });
    } catch (err) {
        res.status(500).json({ message: err.message });
    }
};

// -------------------------
// Update Registration Status (Admin)
// -------------------------
const updateRegistrationStatus = async (req, res) => {
    try {
        const { id } = req.params;
        const { status, reason } = req.body;

        const reg = await Reg.findById(id)
            .populate("student", "name email")
            .populate("event", "title startDateTime endDateTime");

        if (!reg) {
            return res.status(404).json({ message: "Registration not found" });
        }

        const allowed = ["pending", "accepted", "rejected", "attended", "cancelled"];
        if (!allowed.includes(status)) {
            return res.status(400).json({ message: "Invalid status value" });
        }

        if (status === "accepted") {
            reg.status = "accepted";
            reg.rejectionReason = "";

            // ensure ticket is present
            reg.ticket = reg.ticket || {};
            reg.ticket.number = reg.attendanceCode || reg.ticket.number || '';
            reg.ticket.issuedAt = reg.ticket.issuedAt || new Date();
            reg.ticket.qr = reg.ticket.qr || reg.attendanceCode;
            reg.ticket.emailed = false;

            // send ticket email to student (best-effort)
            try {
                const subject = `Your ticket for ${reg.event?.title || 'Event'}`;
                const eventDate = reg.event?.startDateTime ? new Date(reg.event.startDateTime).toLocaleString() : 'Date TBD';
                const html = `<p>Hello ${reg.student?.name || ''},</p>
                <p>Your registration for <strong>${reg.event?.title || ''}</strong> has been <strong>accepted</strong>.</p>
                <p><strong>Attendance Code:</strong> ${reg.attendanceCode}</p>
                <p><strong>When:</strong> ${eventDate}</p>
                <p>Present this code at entry. You can also download your ticket from your dashboard.</p>
                <p>-- Event Team</p>`;

                await sendMail(reg.student.email, subject, `Your attendance code: ${reg.attendanceCode}`, html);
                reg.ticket.emailed = true;
            } catch (mailErr) {
                console.error('[REG] Failed to send ticket email', mailErr && mailErr.message ? mailErr.message : mailErr);
                // continue without failing the whole request
            }
        }

        else if (status === "rejected") {
            if (!reason || reason.trim() === "") {
                return res.status(400).json({ message: "Rejection reason is required" });
            }
            reg.status = "rejected";
            reg.rejectionReason = reason;
        }

        else if (status === "cancelled") {
            reg.status = "cancelled";
            reg.rejectionReason = reason || "";
        }

        else if (status === "attended") {
            // Only allow admin to finalize attendance if student has self-verified
            if (!reg.studentVerified) {
                return res.status(400).json({ message: 'Student has not self-verified attendance yet' });
            }
            reg.status = "attended";
            reg.attendanceConfirmed = true;
            reg.checkedInAt = new Date();
        }

        else {
            reg.status = status;
        }

        await reg.save();

        // return registration object for frontend
        res.json({ registration: reg });

    } catch (err) {
        res.status(500).json({ message: err.message });
    }
};

// -------------------------
// Delete Registration (Admin)
// -------------------------
const deleteRegistration = async (req, res) => {
    try {
        const { id } = req.params;

        const reg = await Reg.findByIdAndDelete(id);

        if (!reg) {
            return res.status(404).json({ message: "Registration not found" });
        }

        res.json({ message: "Registration deleted" });
    } catch (err) {
        res.status(500).json({ message: err.message });
    }
};

module.exports = {
    registerEvent,
    getRegistrations,
    verifyAttendanceCode,
    updateRegistrationStatus,
    deleteRegistration
};
